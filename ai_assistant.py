"""
Claude-помощник для бота «Алиса Невская».

Принцип: модель работает на автора, а не вместо него.
Всё, что видит клиент, проходит через ручное подтверждение.

Функции:
  analyze_question()  — разбор вопроса перед письмом (только для автора)
  draft_letter()      — черновик письма (только для автора)
  suggest_tags()      — предложить метки для карточки клиента
  draft_support()     — черновик ответа в поддержку
  weekly_digest()     — сводка по заказам за период
"""

import logging
import os

log = logging.getLogger("alisa.ai")

ANTHROPIC_API_KEY = os.getenv("ANTHROPIC_API_KEY", "")
# sonnet — рабочая лошадка, opus — для писем, если захочется глубже
MODEL_FAST = os.getenv("AI_MODEL_FAST", "claude-sonnet-4-5")
MODEL_DEEP = os.getenv("AI_MODEL_DEEP", "claude-sonnet-4-5")

_client = None


def available() -> bool:
    """Есть ли ключ и установлена ли библиотека."""
    if not ANTHROPIC_API_KEY:
        return False
    try:
        import anthropic  # noqa: F401
        return True
    except ImportError:
        return False


def client():
    global _client
    if _client is None:
        import anthropic
        _client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)
    return _client


def _call(system: str, prompt: str, max_tokens: int = 1500,
          model: str = None, temperature: float = 1.0) -> str:
    """Один запрос к модели. Возвращает текст или строку с пометкой ошибки."""
    if not available():
        return "[ai] Ключ ANTHROPIC_API_KEY не задан — помощник выключен."

    kwargs = {
        "model": model or MODEL_FAST,
        "max_tokens": max_tokens,
        "system": system,
        "messages": [{"role": "user", "content": prompt}],
    }
    try:
        try:
            resp = client().messages.create(temperature=temperature, **kwargs)
        except TypeError:
            # старые/урезанные версии SDK не принимают temperature
            resp = client().messages.create(**kwargs)
        return "".join(b.text for b in resp.content if b.type == "text").strip()
    except Exception as exc:
        log.error("ai call failed: %s", exc)
        msg = str(exc)
        if "authentication" in msg.lower() or "401" in msg:
            return "[ai] Ключ не принят. Проверь ANTHROPIC_API_KEY."
        if "credit" in msg.lower() or "balance" in msg.lower():
            return "[ai] Закончился баланс в Anthropic Console."
        if "rate" in msg.lower() and "limit" in msg.lower():
            return "[ai] Слишком часто. Подожди минуту и повтори."
        return f"[ai] Не получилось: {msg[:200]}"


# ─────────────────────────────────────────────────────────────
# ГОЛОС АЛИСЫ — основа всех текстовых задач
# ─────────────────────────────────────────────────────────────

VOICE = """Ты помогаешь автору писать письма от лица Алисы Невской.

Кто такая Алиса: 24 года, живёт в Петербурге, пишет письма людям о том,
что их держит. Её жанр — не совет и не консультация, а РАЗРЕШЕНИЕ.
Человек приходит с вопросом, на который у него уже есть ответ, но нет
права его выбрать. Алиса это право даёт.

Как она пишет:
— обращается на «ты», как к близкому, но без фамильярности
— называет вещи своими именами, без обтекаемых формулировок
— не даёт инструкций, планов и списков шагов
— не утешает и не обесценивает боль фразами «всё будет хорошо»
— опирается на детали Петербурга, когда это к месту, но не украшает текст
— короткие абзацы, живая речь, паузы
— может признать, что не знает ответа

Чего в её письмах НЕТ никогда:
— «я тебя понимаю» и «ты не один такой»
— нумерованных советов и техник
— психологических терминов (триггер, проработать, абьюз, границы)
— бодрых финалов и мотивационных лозунгов
— вопросов в конце вместо ответа

Ключевая формула её голоса:
«Я не скажу, что тебе делать. Я скажу, что тебе можно.»"""


FORMAT_SPEC = {
    "письмо": "400–600 слов. Один точный ответ на один вопрос. Плотно, без разгона.",
    "дневник": "700–1000 слов. Через историю или воспоминание Алисы. "
               "Читатель узнаёт себя, а не получает разбор.",
    "сценарий": "1000–1500 слов. Разговор в кафе: Алиса слушает, переспрашивает, "
                "потом говорит всё, что думает. Живая речь, реплики.",
}


# ─────────────────────────────────────────────────────────────
# 1. РАЗБОР ВОПРОСА (только для автора)
# ─────────────────────────────────────────────────────────────

ANALYZE_SYSTEM = """Ты аналитик, который готовит автора к написанию письма.
Твоя работа — увидеть в вопросе то, что человек не сказал прямо.
Пиши сжато, без вступлений и без сочувствия автору. Только суть."""


def analyze_question(question: str, fmt: str, card: str = "") -> str:
    prompt = f"""Вопрос клиента:
{question}

Формат заказа: {fmt}
{f'Что известно о человеке:{chr(10)}{card}' if card else 'Человек пишет впервые.'}

Разбери по пунктам, коротко:

1. О ЧЁМ СПРАШИВАЕТ ПРЯМО — одна фраза
2. О ЧЁМ СПРАШИВАЕТ НА САМОМ ДЕЛЕ — что под вопросом, одна-две фразы
3. СОСТОЯНИЕ — в какой точке человек: решает, оправдывается, прощается, застрял
4. ЧЕГО БОИТСЯ — чего именно, конкретно
5. КАКОЕ РАЗРЕШЕНИЕ ЕМУ НУЖНО — что Алисе стоит разрешить этому человеку
6. ЧЕГО НЕЛЬЗЯ ПИСАТЬ — что в этом случае прозвучит фальшиво или ранит
7. МЕТКИ — 2-4 из списка: тревожность, выгорание, отношения, работа, семья,
   самооценка, одиночество, поиск себя, утрата, деньги, рационален,
   эмоционален, ищет разрешения, ищет план"""
    return _call(ANALYZE_SYSTEM, prompt, max_tokens=900, temperature=0.7)


# ─────────────────────────────────────────────────────────────
# 2. ЧЕРНОВИК ПИСЬМА (только для автора, не для клиента)
# ─────────────────────────────────────────────────────────────

def draft_letter(question: str, fmt: str, card: str = "",
                 notes: str = "", deep: bool = False) -> str:
    spec = FORMAT_SPEC.get(fmt, FORMAT_SPEC["письмо"])
    prompt = f"""Напиши черновик письма.

Вопрос человека:
{question}

Формат: {fmt} — {spec}
{f'''
Что известно об этом человеке (учти, но не упоминай прямо, что ведёшь записи):
{card}''' if card else ''}
{f'''
Заметки автора о характере человека:
{notes}''' if notes else ''}

Требования:
— начни сразу с сути, без «привет» и «спасибо за твой вопрос»
— не подписывайся
— это черновик для автора: он будет править, дописывать личное и решать,
  что оставить. Не пытайся сделать «идеально гладко» — лучше точно."""

    return _call(VOICE, prompt, max_tokens=2500,
                 model=MODEL_DEEP if deep else MODEL_FAST,
                 temperature=1.0)


# ─────────────────────────────────────────────────────────────
# 3. МЕТКИ ДЛЯ КАРТОЧКИ
# ─────────────────────────────────────────────────────────────

TAGS = ["тревожность", "выгорание", "отношения", "работа", "семья",
        "самооценка", "одиночество", "поиск себя", "утрата", "деньги",
        "рационален", "эмоционален", "ищет разрешения", "ищет план"]


def suggest_tags(questions: list) -> str:
    joined = "\n---\n".join(questions[:8])
    prompt = f"""Вопросы одного человека за всё время:
{joined}

Выбери 3-5 меток из списка: {', '.join(TAGS)}

Ответь только метками через запятую, без пояснений."""
    return _call("Ты сжато классифицируешь. Только запрошенный формат ответа.",
                 prompt, max_tokens=120, temperature=0.3)


# ─────────────────────────────────────────────────────────────
# 4. ЧЕРНОВИК ОТВЕТА В ПОДДЕРЖКУ
# ─────────────────────────────────────────────────────────────

SUPPORT_SYSTEM = """Ты пишешь черновики ответов на обращения в поддержку
от лица Алисы. Тон: спокойный, короткий, по делу, без корпоративной вежливости
и без «приносим извинения за неудобства». Максимум 3-4 предложения.
Если человек недоволен письмом — предложить переписать бесплатно."""


def draft_support(message: str, context: str = "") -> str:
    prompt = f"""Обращение клиента:
{message}
{f'{chr(10)}Контекст: {context}' if context else ''}

Напиши короткий ответ."""
    return _call(SUPPORT_SYSTEM, prompt, max_tokens=400, temperature=0.8)


# ─────────────────────────────────────────────────────────────
# 5. НЕДЕЛЬНАЯ СВОДКА
# ─────────────────────────────────────────────────────────────

DIGEST_SYSTEM = """Ты аналитик небольшого проекта. Отвечай сжато, конкретно,
без похвал и без общих слов вроде «важно продолжать в том же духе».
Если данных мало для вывода — скажи это прямо."""


def weekly_digest(stats: dict, questions: list) -> str:
    qs = "\n".join(f"— {q[:160]}" for q in questions[:20]) or "нет заказов"
    prompt = f"""Данные за период:
заказов всего: {stats.get('total', 0)}
оплачено: {stats.get('paid', 0)}
отправлено писем: {stats.get('done', 0)}
не оплачено: {stats.get('pending', 0)}
выручка: {stats.get('revenue', 0)} ₽
средняя оценка: {stats.get('avg_rating', '—')}
повторных клиентов: {stats.get('repeat', 0)}

Вопросы, с которыми приходили:
{qs}

Дай сводку:
1. ЧТО ПРОИСХОДИТ — 2-3 фразы по цифрам
2. ТЕМЫ — какие темы повторяются, что это говорит об аудитории
3. ЧТО СТОИТ СДЕЛАТЬ — 2-3 конкретных действия, без общих советов
4. НА ЧТО СМОТРЕТЬ ДАЛЬШЕ — одна метрика, которая сейчас важнее прочих"""
    return _call(DIGEST_SYSTEM, prompt, max_tokens=1100, temperature=0.7)
