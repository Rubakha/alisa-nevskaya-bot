PAIN_HINTS = {
    "Расставание": "человек переживает разрыв отношений",
    "Обида": "человека что-то задело, и это не отпускает",
    "Одиночество": "человек чувствует, что рядом никого нет по-настоящему",
    "Страх": "человека что-то останавливает, парализует",
    "Недосказанность": "человек не сказал что-то важное и носит это в себе",
}


def diagnostic_question(pain_title: str, history: list) -> str:
    """Один уточняющий вопрос для диагностической беседы.

    history — список пар (вопрос, ответ), уже заданных в этой сессии.
    Пустой список — это первый вопрос.
    """
    hint = PAIN_HINTS.get(pain_title, "")
    asked = "\n".join(f"Я спросила: {q}\nОн ответил: {a}" for q, a in history)
    prompt = f"""Человек выбрал тему: «{pain_title}» ({hint}).
{f'Уже было в разговоре:{chr(10)}{asked}' if asked else 'Это первый вопрос, разговор только начинается.'}

Задай один короткий уточняющий вопрос, чтобы лучше понять его состояние.
Требования:
— 1-2 предложения, без нумерации и вступлений вроде «понимаю»
— не спрашивай то, что уже спрашивала
— вопрос должен звучать как от человека, который правда хочет понять, а не
  как анкета
— ответь только текстом вопроса, без кавычек и пояснений"""
    return _call(THERAPIST_VOICE, prompt, max_tokens=200, temperature=0.9)


def mirror_reflection(pain_title: str, answers: list) -> str:
    """Короткий психологический разбор-отражение (3-4 предложения)."""
    joined = "\n".join(f"— {a}" for a in answers)
    prompt = f"""Тема: «{pain_title}».
Ответы человека на уточняющие вопросы:
{joined}

Напиши короткий разбор-отражение (3-4 предложения): опиши то, что человек
сейчас чувствует, будто смотришь в зеркало вместе с ним. Используй метафоры
дождя, одиночества, внутренних тупиков и поиска опор — только если они
действительно ложатся на его ситуацию.

Требования:
— эмпатично, глубоко, без токсичного позитива
— не давай советов и не делай выводов на будущее — только назови то, что
  есть сейчас
— ответь только текстом разбора, без заголовков"""
    return _call(THERAPIST_VOICE, prompt, max_tokens=400, temperature=0.9)


def generate_letter(pain_title: str, answers: list, mirror: str,
                    gift_for: str = None) -> str:
    """Финальное письмо клиенту — уходит без правки, целиком."""
    joined = "\n".join(f"— {a}" for a in answers)
    addressee = (
        f"Письмо адресовано другому человеку — {gift_for}. "
        f"Обращайся напрямую к нему, будто пишешь именно ему, а не тому, "
        f"кто оформил заказ."
        if gift_for else
        "Обращайся к тому, кто отвечал на вопросы — это ему письмо."
    )
    prompt = f"""Тема: «{pain_title}».
Ответы человека:
{joined}

Разбор, который уже показан человеку:
{mirror}

{addressee}

Напиши глубокое, художественное письмо с сильной эмоциональной кульминацией.
Используй конкретные детали из ответов — то, что он на самом деле сказал,
а не общие слова о теме.

Требования:
— 350-550 слов
— начни сразу с сути, без «привет» и «спасибо, что написал»
— не подписывайся
— это финальный текст, который уходит человеку как есть — без пометок
  «черновик» и без внутренних комментариев"""
    text = _call(THERAPIST_VOICE, prompt, max_tokens=1800,
                 model=MODEL_DEEP, temperature=1.0)
    return text if text.startswith("[ai]") else _airy(text)


