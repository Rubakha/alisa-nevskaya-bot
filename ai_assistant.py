TAGS = ["тревожность", "выгорание", "отношения", "работа", "семья",
        "самооценка", "одиночество", "поиск себя", "утрата", "деньги",
        "рационален", "эмоционален", "ищет разрешения", "ищет план"]


def suggest_tags(questions: list) -> str:
    joined = "\n---\n".join(questions[:8])
    prompt = f"""Вопросы одного человека за всё время:
{joined}

Выбери 3-5 меток из списка: {', '.join(TAGS)}

Ответь только метками через запятую, без пояснений."""
    return _call("Ты сжато классифицируешь. Только запрошенный формат ответа.",
                 prompt, max_tokens=120, temperature=0.3)


