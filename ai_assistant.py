"""
Claude-помощник для бота «Алиса Невская».

Принцип: модель работает на автора, а не вместо него.
Всё, что видит клиент, проходит через ручное подтверждение.

Функции:
  analyze_question()  — разбор вопроса перед письмом (только для автора)
  draft_letter()      — черновик письма (только для автора)
  suggest_tags()      — предложить метки для карточки клиента
  draft_support()     — черновик ответа в поддержку
  weekly_digest()     — сводка по заказам за период
"""

import logging
import os
import re

log = logging.getLogger("alisa.ai")

ANTHROPIC_API_KEY = os.getenv("ANTHROPIC_API_KEY", "")
# sonnet — рабочая лошадка, opus — для писем, если захочется глубже
MODEL_FAST = os.getenv("AI_MODEL_FAST", "claude-sonnet-4-5")
MODEL_DEEP = os.getenv("AI_MODEL_DEEP", "claude-sonnet-4-5")

_client = None


def available() -> bool:
    """Есть ли ключ и установлена ли библиотека."""
    if not ANTHROPIC_API_KEY:
        return False
    try:
        import anthropic  # noqa: F401
        return True
    except ImportError:
        return False


def client():
    global _client
    if _client is None:
        import anthropic
        _client = anthropic.Anthropic(api_key=ANTHROPIC_API_KEY)
    return _client


def _airy(text: str) -> str:
    """Абзацы разделены пустой строкой; строка подписи «— Имя» остаётся вплотную к своему абзацу."""
    import re
    text = (text or "").replace("\r\n", "\n").strip()
    text = re.sub(r"\n(?!\n)(?!\s*—)", "\n\n", text)  # одиночный перенос → пустая строка
    return re.sub(r"\n{3,}", "\n\n", text)



def _call(system: str, prompt: str, max_tokens: int = 1500,
          model: str = None, temperature: float = None) -> str:
    """Один запрос к модели. Возвращает текст или строку с пометкой ошибки.

    Параметр temperature оставлен в сигнатуре для совместимости с вызовами,
    но в актуальном SDK (anthropic 1.x) он не поддерживается и игнорируется.
    """
    if not available():
        return "[ai] Ключ ANTHROPIC_API_KEY не задан — помощник выключен."

    try:
        resp = client().messages.create(
            model=model or MODEL_FAST,
            max_tokens=max_tokens,
            system=system,
            messages=[{"role": "user", "content": prompt}],
        )
        return "".join(b.text for b in resp.content if b.type == "text").strip()
    except Exception as exc:
        log.error("ai call failed: %s", exc)
        msg = str(exc)
        if "authentication" in msg.lower() or "401" in msg:
            return "[ai] Ключ не принят. Проверь ANTHROPIC_API_KEY."
        if "credit" in msg.lower() or "balance" in msg.lower():
            return "[ai] Закончился баланс в Anthropic Console."
        if "rate" in msg.lower() and "limit" in msg.lower():
            return "[ai] Слишком часто. Подожди минуту и повтори."
        return f"[ai] Не получилось: {msg[:200]}"


def list_models() -> str:
    """Показывает модели, доступные текущему ключу.

    Нужно, чтобы не угадывать имя модели: вписываешь в AI_MODEL_FAST
    ровно то, что вернул этот список.
    """
    if not available():
        return "[ai] Ключ ANTHROPIC_API_KEY не задан."
    try:
        models = client().models.list(limit=20)
        names = [m.id for m in models.data]
        if not names:
            return "[ai] Ключ принят, но список моделей пуст."
        return "Доступные модели:\n" + "\n".join(f"· {n}" for n in names)
    except Exception as exc:
        msg = str(exc)
        if "authentication" in msg.lower() or "401" in msg:
            return "[ai] Ключ не принят. Проверь ANTHROPIC_API_KEY."
        return f"[ai] Не получилось получить список: {msg[:200]}"


def selftest() -> str:
    """Полная проверка связки: ключ, модель, ответ."""
    if not available():
        return ("❌ Помощник выключен.\n"
                "Нужно: pip install anthropic и переменная ANTHROPIC_API_KEY.")
    lines = [f"Модель: {MODEL_FAST}"]
    out = _call("Отвечай одним словом.", "Скажи слово: работает", max_tokens=20)
    if out.startswith("[ai]"):
        lines.append(f"❌ {out}")
        lines.append("")
        lines.append(list_models())
    else:
        lines.append(f"✅ Ответ модели: {out}")
    return "\n".join(lines)


