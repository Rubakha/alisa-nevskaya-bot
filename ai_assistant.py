def weekly_digest(stats: dict, questions: list) -> str:
    qs = "\n".join(f"— {q[:160]}" for q in questions[:20]) or "нет заказов"
    prompt = f"""Данные за период:
заказов всего: {stats.get('total', 0)}
оплачено: {stats.get('paid', 0)}
отправлено писем: {stats.get('done', 0)}
не оплачено: {stats.get('pending', 0)}
выручка: {stats.get('revenue', 0)} ₽
средняя оценка: {stats.get('avg_rating', '—')}
повторных клиентов: {stats.get('repeat', 0)}

Вопросы, с которыми приходили:
{qs}

Дай сводку:
1. ЧТО ПРОИСХОДИТ — 2-3 фразы по цифрам
2. ТЕМЫ — какие темы повторяются, что это говорит об аудитории
3. ЧТО СТОИТ СДЕЛАТЬ — 2-3 конкретных действия, без общих советов
4. НА ЧТО СМОТРЕТЬ ДАЛЬШЕ — одна метрика, которая сейчас важнее прочих"""
    return _call(DIGEST_SYSTEM, prompt, max_tokens=1100, temperature=0.7)


