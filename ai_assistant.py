def draft_letter(question: str, fmt: str, card: str = "",
                 notes: str = "", deep: bool = False) -> str:
    spec = FORMAT_SPEC.get(fmt, FORMAT_SPEC["письмо"])
    prompt = f"""Напиши черновик письма.

Вопрос человека:
{question}

Формат: {fmt} — {spec}
{f'''
Что известно об этом человеке (учти, но не упоминай прямо, что ведёшь записи):
{card}''' if card else ''}
{f'''
Заметки автора о характере человека:
{notes}''' if notes else ''}

Требования:
— начни сразу с сути, без «привет» и «спасибо за твой вопрос»
— не подписывайся
— это черновик для автора: он будет править, дописывать личное и решать,
  что оставить. Не пытайся сделать «идеально гладко» — лучше точно."""

    return _call(VOICE, prompt, max_tokens=2500,
                 model=MODEL_DEEP if deep else MODEL_FAST,
                 temperature=1.0)


