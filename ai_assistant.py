ANALYZE_SYSTEM = """Ты аналитик, который готовит автора к написанию письма.
Твоя работа — увидеть в вопросе то, что человек не сказал прямо.
Пиши сжато, без вступлений и без сочувствия автору. Только суть."""


def analyze_question(question: str, fmt: str, card: str = "") -> str:
    prompt = f"""Вопрос клиента:
{question}

Формат заказа: {fmt}
{f'Что известно о человеке:{chr(10)}{card}' if card else 'Человек пишет впервые.'}

Разбери по пунктам, коротко:

1. О ЧЁМ СПРАШИВАЕТ ПРЯМО — одна фраза
2. О ЧЁМ СПРАШИВАЕТ НА САМОМ ДЕЛЕ — что под вопросом, одна-две фразы
3. СОСТОЯНИЕ — в какой точке человек: решает, оправдывается, прощается, застрял
4. ЧЕГО БОИТСЯ — чего именно, конкретно
5. КАКОЕ РАЗРЕШЕНИЕ ЕМУ НУЖНО — что Алисе стоит разрешить этому человеку
6. ЧЕГО НЕЛЬЗЯ ПИСАТЬ — что в этом случае прозвучит фальшиво или ранит
7. МЕТКИ — 2-4 из списка: тревожность, выгорание, отношения, работа, семья,
   самооценка, одиночество, поиск себя, утрата, деньги, рационален,
   эмоционален, ищет разрешения, ищет план"""
    return _call(ANALYZE_SYSTEM, prompt, max_tokens=900, temperature=0.7)


