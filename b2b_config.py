"""Корпоративная линейка к Новому году (B2B): пакеты, цены и лимиты. Все цифры — только здесь,
чтобы владелец менял их в одном месте (или переменными окружения для даты и реквизитов)."""
import os

SALES_START = os.getenv("B2B_SALES_START", "2026-11-01")  # продажи открываются с этой даты (YYYY-MM-DD)

# ── «Новый год коллективу»: цена по размеру команды (до N человек → цена), ₽ ──
TEAM_TIERS = [(10, 4900), (30, 9900), (60, 14900)]
TEAM_MAX = TEAM_TIERS[-1][0]
TEAM_DEPT_CARD_PRICE = 0        # общая открытка отдела: 0 = входит в цену, иначе доплата в ₽

# ── «Клиентам компании»: пакет (сколько писем) → цена, ₽ ──
CLIENT_PACKS = [(100, 9900), (500, 34900), (1000, 59900)]
CLIENT_MAX = CLIENT_PACKS[-1][0]

# ── «Дни рождения команды» (каркас): до N человек → цена в месяц, ₽ ──
BD_TIERS = [(50, 2990), (200, 5990)]

CARD_PRODUCT = "newyear"        # какие фоны открыток брать из assets/postcards
CARD_SEED_VARIANTS = 6          # разных «композиций» фона на пакет, чтобы открытки не были близнецами

SMALL_PAY_LIMIT = 15000         # до этой суммы можно оплатить картой/СБП как в B2C; выше — только счёт
PARALLEL = int(os.getenv("B2B_PARALLEL", "3"))  # одновременных запросов к модели при пакетной генерации
RETRIES = 3                     # попыток на одно письмо
RETRY_PAUSE = 2                 # пауза перед повтором, с (умножается на номер попытки)
PREVIEW_COUNT = 3               # сколько превью показываем до оплаты
PREVIEW_ROUNDS = 3              # сколько раз можно запросить «другие варианты» (защита платных вызовов)
MAX_PROJECTS_PER_DAY = 5        # новых заказов с превью от одного человека за сутки (превью — платные вызовы модели)
ZIP_PART_BYTES = 45 * 1024 * 1024  # Telegram принимает файл бота до 50 МБ — режем архив на части
MAX_UPLOAD_BYTES = 2 * 1024 * 1024  # список (CSV/XLSX) и логотип

# Реквизиты исполнителя для счёта (показываем юрлицам). Задаются переменной окружения, в коде их нет.
REQUISITES = os.getenv("B2B_REQUISITES", "")

TONES = {
    "warm": "🌿 Тёплый",
    "formal": "🎩 Официальный",
    "humor": "✨ С юмором",
}

PACKAGES = {
    "team": {"icon": "🎄", "title": "Новый год коллективу"},
    "cli": {"icon": "💌", "title": "Клиентам компании"},
    "bd": {"icon": "🎂", "title": "Дни рождения команды"},
}


def team_price(n):
    """Цена пакета «коллективу» по числу сотрудников; None, если команда больше TEAM_MAX."""
    for limit, price in TEAM_TIERS:
        if n <= limit:
            return price
    return None


def client_pack(n, chosen=None):
    """Наименьший пакет, в который помещается n писем (но не меньше выбранного). None — больше максимума."""
    for size, price in CLIENT_PACKS:
        if n <= size and (chosen is None or size >= chosen):
            return size, price
    return None


def bd_price(size):
    return dict(BD_TIERS).get(size)
